window.showToast = function(message, type = "error") {
  let toastContainer = document.getElementById("toast-container");
  if (!toastContainer) {
    toastContainer = document.createElement("div");
    toastContainer.id = "toast-container";
    toastContainer.style.position = "fixed";
    toastContainer.style.bottom = "30px";
    toastContainer.style.right = "30px";
    toastContainer.style.zIndex = "9999";
    toastContainer.style.display = "flex";
    toastContainer.style.flexDirection = "column";
    toastContainer.style.gap = "10px";
    document.body.appendChild(toastContainer);
  }

  const toast = document.createElement("div");
  toast.style.background = type === "error" ? "rgba(220, 53, 69, 0.95)" : "rgba(40, 167, 69, 0.95)";
  toast.style.color = "#fff";
  toast.style.padding = "15px 25px";
  toast.style.borderRadius = "12px";
  toast.style.boxShadow = "0 8px 32px rgba(0, 0, 0, 0.2)";
  toast.style.backdropFilter = "blur(10px)";
  toast.style.fontFamily = "inherit";
  toast.style.fontSize = "15px";
  toast.style.fontWeight = "500";
  toast.style.display = "flex";
  toast.style.alignItems = "center";
  toast.style.gap = "12px";
  toast.style.transform = "translateX(120%)";
  toast.style.opacity = "0";
  toast.style.transition = "all 0.4s cubic-bezier(0.68, -0.55, 0.265, 1.55)";
  
  const icon = document.createElement("i");
  icon.className = type === "error" ? "fa-solid fa-circle-exclamation" : "fa-solid fa-circle-check";
  icon.style.fontSize = "20px";

  const text = document.createElement("span");
  text.textContent = message;

  toast.appendChild(icon);
  toast.appendChild(text);
  toastContainer.appendChild(toast);

  setTimeout(() => {
    toast.style.transform = "translateX(0)";
    toast.style.opacity = "1";
  }, 10);

  setTimeout(() => {
    toast.style.transform = "translateX(120%)";
    toast.style.opacity = "0";
    setTimeout(() => toast.remove(), 400);
  }, 3500);
};

document.addEventListener("DOMContentLoaded", () => {
    let currentLang = localStorage.getItem('appLang') || 'en';
    
    function applyLang(lang) {
        document.documentElement.lang = lang;
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
        
        const langTexts = document.querySelectorAll('#langText');
        langTexts.forEach(langText => {
            langText.textContent = lang === 'en' ? 'عربي' : 'English';
        });

        document.querySelectorAll('[data-i18n]').forEach(elem => {
            const key = elem.getAttribute('data-i18n');
            if (globalTranslations[lang] && globalTranslations[lang][key]) {
                elem.textContent = globalTranslations[lang][key];
            }
        });

        document.querySelectorAll('[data-i18n-ph]').forEach(elem => {
            const key = elem.getAttribute('data-i18n-ph');
            if (globalTranslations[lang] && globalTranslations[lang][key]) {
                elem.placeholder = globalTranslations[lang][key];
            }
        });
        
        // special case for user area text when username is present
        const userInfoElem = document.getElementById('userInfo');
        if (userInfoElem && !userInfoElem.hasAttribute('data-i18n')) {
             let name = userInfoElem.textContent.replace('Hello, ', '').replace('مرحباً، ', '');
             userInfoElem.textContent = (lang === 'en' ? 'Hello, ' : 'مرحباً، ') + name;
        }

        // special case for profile dynamic translations if element has no data-i18n but is populated dynamically
        const profileStatusElem = document.getElementById('profileStatus');
        if (profileStatusElem && profileStatusElem.textContent) {
            profileStatusElem.textContent = lang === 'en' ? 'Logged In' : 'تم تسجيل الدخول';
        }

        // Special case for Categories Menu dropdown
        const catLinks = document.querySelectorAll('#categoriesMenu a');
        catLinks.forEach(a => {
            if (a.hasAttribute('data-en-name')) {
                a.textContent = translateCategoryName(a.getAttribute('data-en-name'), lang);
            }
        });
    }
    
    function translateCategoryName(name, lang) {
        if (lang === 'en') return name;
        const dict = {
            "Bed": "سرير", "Chair": "كرسي", "Table": "طاولة", "Sofas": "كنبة",
            "Carpet": "سجادة", "Television": "تلفزيون", "Refrigerator": "ثلاجة",
            "Microwave": "ميكروويف", "Dishwasher": "غسالة أطباق", "Toaster": "محمصة",
            "Waffle Iron": "صانع وافل", "Vacuum Cleaner": "مكنسة كهربائية",
            "Electric Fan": "مروحة", "Hand Blower": "مجفف هواء", "Coffe Maker": "ماكينة قهوة",
            "Teapot": "إبريق شاي", "Crock Pot": "حلة طهي", "Mixing Bowl": "وعاء خلط",
            "Frying Pan": "مقلاة", "Pitcher": "إبريق", "Salt Shaker": "ملاحة",
            "Cleaver": "ساطور", "Stove": "بوتاجاز", "Wardrobe": "دولاب", "Chiffonier": "تسريحة"
        };
        for (let key in dict) {
            if (name.toLowerCase().includes(key.toLowerCase())) return dict[key];
        }
        return name;
    }
    
    // Auto-populate Categories Menu to ensure it respects language
    const categoriesMenu = document.getElementById("categoriesMenu");
    if (categoriesMenu) {
        fetch("http://127.0.0.1:8000/categories")
            .then(res => res.json())
            .then(data => {
                categoriesMenu.innerHTML = "";
                data.categories.forEach(cat => {
                    const a = document.createElement("a");
                    a.href = `category.html?class=${encodeURIComponent(cat.id)}`;
                    
                    let cleanName = cat.name.replace("_dataset", "").replace(" dataset", "").replace("_", " ").replace(/\b\w/g, l => l.toUpperCase());
                    a.setAttribute("data-en-name", cleanName);
                    
                    a.textContent = translateCategoryName(cleanName, currentLang);
                    categoriesMenu.appendChild(a);
                });
            })
            .catch(err => {
                console.error("Error loading categories:", err);
            });
    }
    
    applyLang(currentLang);
    
    const langToggleBtns = document.querySelectorAll('#langToggle');
    langToggleBtns.forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            currentLang = currentLang === 'en' ? 'ar' : 'en';
            localStorage.setItem('appLang', currentLang);
            applyLang(currentLang);
            window.dispatchEvent(new Event('langChanged'));
        });
    });

    // ==========================================
    // Sync Topbar Auth UI across all pages
    // ==========================================
    const isLoggedIn = localStorage.getItem("isLoggedIn") === "true" || sessionStorage.getItem("isLoggedIn") === "true";
    const authBtn = document.getElementById("authBtn");
    const authText = document.getElementById("authText");
    const settingsBtn = document.getElementById("settingsBtn");
    const dropdownMenu = document.getElementById("dropdownMenu");
    const userInfoElem = document.getElementById("userInfo");

    if (authBtn) {
        if (isLoggedIn) {
            if (authText) {
                authText.textContent = currentLang === 'ar' ? "تسجيل الخروج" : "Logout";
                authText.setAttribute('data-i18n', 'logout_text');
            }
            if (settingsBtn) settingsBtn.style.display = "inline-flex";
            
            let displayName = "User";
            try {
                const cached = localStorage.getItem("lastUserProfileData");
                if (cached) {
                    const data = JSON.parse(cached);
                    displayName = data.fname || data.username || "User";
                }
            } catch(e) {}
            
            if (userInfoElem) {
                userInfoElem.textContent = (currentLang === 'ar' ? "مرحباً، " : "Hello, ") + displayName;
                userInfoElem.removeAttribute('data-i18n');
            }
        } else {
            if (authText) {
                authText.textContent = currentLang === 'ar' ? "تسجيل الدخول" : "Login";
                authText.setAttribute('data-i18n', 'login_text');
            }
            if (settingsBtn) settingsBtn.style.display = "none";
            if (dropdownMenu) dropdownMenu.classList.remove("show");
            if (userInfoElem) {
                userInfoElem.textContent = currentLang === 'ar' ? "مرحباً، مستخدم" : "Hello, User";
                userInfoElem.setAttribute('data-i18n', 'hello_user');
            }
        }
    }
});
